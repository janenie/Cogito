grep -q 'name="HumanBreakRoomEntrance"' "$scene"
grep -q 'name="HumanBreakRoomVisit"' "$scene"
grep -q 'name="HumanSofaApproach"' "$scene"
grep -q 'name="HumanSofaStop"' "$scene"
grep -q 'route_root = NodePath("../FriendlyHumanNPCPath")' "$scene"
grep -q 'walk_speed = 0.35' "$scene"

grep -q 'type="CharacterBody3D"' "$npc_scene"
grep -q 'path="res://addons/cogito/DemoScenes/friendly_human_npc.gd"' "$npc_scene"
grep -q 'name="Visual"' "$npc_scene"
grep -q 'name="Body"' "$npc_scene"
grep -q 'name="Head"' "$npc_scene"
grep -q 'name="BasicInteraction"' "$npc_scene"
grep -q 'interaction_text = "Talk"' "$npc_scene"
grep -q 'name="NavigationAgent3D" type="NavigationAgent3D"' "$npc_scene"
grep -q 'navigation_agent = NodePath("NavigationAgent3D")' "$npc_scene"
grep -q '@export var navigation_agent: NavigationAgent3D' "$npc_script"
grep -q 'navigation_agent.target_position = target.global_position' "$npc_script"
grep -q 'navigation_agent.get_next_path_position()' "$npc_script"
grep -q 'velocity_computed.connect(_on_navigation_agent_velocity_computed)' "$npc_script"
grep -q 'func _on_navigation_agent_velocity_computed(safe_velocity: Vector3)' "$npc_script"
grep -q '@export var use_navigation_agent: bool = true' "$npc_script"
grep -q 'func _get_next_route_position(target: Node3D)' "$npc_script"
grep -q 'if not use_navigation_agent or navigation_agent == null:' "$npc_script"
grep -q 'navigation_agent.is_target_reachable()' "$npc_script"
grep -q '@export var navigation_probe_steps: int = 3' "$npc_script"
grep -q '@export var navigation_probe_step_distance: float = 0.35' "$npc_script"
grep -q 'func _is_navigation_path_clear(next_position: Vector3)' "$npc_script"

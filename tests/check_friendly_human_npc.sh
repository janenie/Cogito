npc_script="addons/cogito/DemoScenes/friendly_human_npc.gd"

test -f "$npc_scene"
test -f "$npc_script"

grep -q 'name="FriendlyHumanNPC"' "$scene"
grep -q 'path="res://addons/cogito/DemoScenes/friendly_human_npc.tscn"' "$scene"
grep -q 'name="FriendlyHumanNPCPath"' "$scene"
grep -q 'name="HumanMeetingRoomStart"' "$scene"
grep -q 'name="HumanMeetingRoomDoorInside"' "$scene"

grep -q 'var using_navigation := next_position != target.global_position' "$npc_script"
grep -q '@export var auto_open_doors: bool = true' "$npc_script"
grep -q '@export var door_close_distance: float = 2.2' "$npc_script"
grep -q '@export var meeting_room_arrival_distance: float = 0.25' "$npc_script"
grep -q '@export var wait_at_route_points: bool = false' "$npc_script"
grep -q '@export var wait_time_min: float = 5.0' "$npc_script"
grep -q '@export var wait_time_max: float = 60.0' "$npc_script"
grep -q '@export var no_wait_route_point_names: Array\[String\] = \[' "$npc_script"
grep -q '@export var chair_search_distance: float = 2.0' "$npc_script"
grep -q '@export var allow_sitting: bool = false' "$npc_script"
grep -q '@export var sit_chair_parent_name: String = "MEETING_ROOM"' "$npc_script"
grep -q '@export var sit_route_point_names: Array\[String\] = \["HumanMeetingRoomStart"\]' "$npc_script"
grep -q 'func _open_nearby_doors()' "$npc_script"
grep -q 'door.open_door(self)' "$npc_script"
grep -q 'func _close_opened_doors()' "$npc_script"
grep -q 'door.close_door(self)' "$npc_script"
grep -q 'func _begin_route_wait(target: Node3D)' "$npc_script"
grep -q 'func _should_wait_at_route_point(target: Node3D)' "$npc_script"
grep -q 'if not wait_at_route_points:' "$npc_script"
grep -q 'if not _should_wait_at_route_point(target):' "$npc_script"
grep -q 'func _try_sit_nearby_chair()' "$npc_script"
grep -q 'func _can_sit_at_route_point(target: Node3D)' "$npc_script"
grep -q 'if not allow_sitting:' "$npc_script"
grep -q 'return sit_route_point_names.has(target.name)' "$npc_script"
grep -q 'func _is_node_inside_named_parent(node: Node, parent_name: String)' "$npc_script"
grep -q 'var _stand_position_before_sit := Vector3.ZERO' "$npc_script"
grep -q 'func _restore_standing_position_after_sit()' "$npc_script"
grep -q 'func _set_sitting_pose(is_sitting: bool)' "$npc_script"
grep -q 'avoidance_enabled = true' "$npc_scene"

if grep -q 'CogitoNPC/cogito_npc.tscn' "$npc_scene"; then
	echo "friendly_human_npc.tscn must not instance the robot NPC template" >&2
	exit 1
fi
